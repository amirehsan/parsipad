/**
 * Get translation for a key
 * @param {string} key - Translation key
 * @param {string} lang - Language code ('en' or 'fa')
 * @returns {string}
 */
export function t(key, lang = 'en') {
  return translations[lang]?.[key] || translations.en[key] || key;
}

/**
 * Apply translations to all elements with data-i18n attribute
 * @param {string} lang - Language code
 */
export function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key, lang);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key, lang);
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key, lang);
    // Mirror the title onto aria-label so screen readers see it too.
    // Devs can opt out by also setting data-i18n-aria-label="" explicitly.
    if (!el.hasAttribute('aria-label') && !el.hasAttribute('data-i18n-aria-label')) {
      el.setAttribute('aria-label', t(key, lang));
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    el.setAttribute('aria-label', t(key, lang));
  });

  // Set document direction
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
}
